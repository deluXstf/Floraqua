/// Собрать структурированный блок условий содержания для prompt.
String buildGeminiContextBlock({
  String? potSize,
  String? location,
  String? hasDrainage,
  String? userNotes,
}) {
  final lines = <String>[];
  if (potSize != null && potSize.isNotEmpty) {
    lines.add('- Размер горшка: $potSize');
  }
  if (location != null && location.isNotEmpty) {
    lines.add('- Место расположения: $location');
  }
  if (hasDrainage != null && hasDrainage.isNotEmpty) {
    lines.add('- Дренажные отверстия в горшке: $hasDrainage');
  }
  if (userNotes != null && userNotes.trim().isNotEmpty) {
    lines.add('- Заметки пользователя: ${userNotes.trim()}');
  }

  if (lines.isEmpty) return '';

  return '\n\nДополнительная информация об условиях содержания этого растения '
      '(обязательно учти её при оценке состояния, поливе и советах по уходу):\n'
      '${lines.join('\n')}';
}

